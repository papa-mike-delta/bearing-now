import { test, expect } from "./fixtures";
import { InboxPage } from "./pages/InboxPage";

test("ordinary and Coach edits refresh graph, list and detail through the same policy", async ({ page }) => {
  const app = new InboxPage(page);
  await app.goto();
  const original = await app.seed({ title: InboxPage.unique("write original"), type: "task" });
  const userTitle = InboxPage.unique("user title");
  const coachTitle = InboxPage.unique("coach title");
  await app.reload();
  await app.navigate("Brain Graph");
  const graphSearch = page.getByPlaceholder("Search nodes…");
  await graphSearch.fill(original.title);
  await expect(page.getByText("1 match · non-matches dimmed", { exact: true })).toBeVisible();
  await app.navigate("Inbox");
  await app.row(original.title).getByTitle("Edit", { exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.locator("input").first().fill(userTitle);
  const closedUserLease = page.waitForResponse((r) => r.request().method() === "DELETE" && r.url().endsWith(`/api/items/${original.id}/open`));
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(dialog).toBeHidden();
  await closedUserLease;
  await expect(page.getByText(userTitle, { exact: true })).toBeVisible();
  await page.getByText(userTitle, { exact: true }).click();
  await expect(dialog.getByRole("heading", { name: userTitle, exact: true })).toBeVisible();
  const closedDetailLease = page.waitForResponse((r) => r.request().method() === "DELETE" && r.url().endsWith(`/api/items/${original.id}/open`));
  await page.keyboard.press("Escape"); await closedDetailLease;
  const userGraph = page.waitForResponse((r) => r.request().method() === "GET" && r.url().includes("/api/graph"));
  await app.navigate("Brain Graph");
  expect((await (await userGraph).json()).nodes).toEqual(expect.arrayContaining([expect.objectContaining({ id: original.id, title: userTitle })]));
  await graphSearch.fill(userTitle);
  await expect(page.getByText("1 match · non-matches dimmed", { exact: true })).toBeVisible();

  const current = await (await page.request.get(`/api/items/${original.id}`)).json();
  await page.locator("summary").filter({ hasText: /^Coach$/ }).click();
  await page.getByLabel("Tool", { exact: true }).selectOption("updateItem");
  await page.getByLabel("Arguments (JSON)").fill(JSON.stringify({ id: original.id, revision: current.revision, data: { title: coachTitle, status: "done" } }));
  const coachWrite = page.waitForResponse((r) => r.request().method() === "POST" && r.url().endsWith("/api/coach"));
  const coachGraph = page.waitForResponse((r) => r.request().method() === "GET" && r.url().includes("/api/graph"));
  await page.getByRole("button", { name: "Run tool", exact: true }).click();
  expect((await coachWrite).status()).toBe(200);
  expect((await (await coachGraph).json()).nodes).toEqual(expect.arrayContaining([expect.objectContaining({ id: original.id, title: coachTitle, status: "done" })]));
  await graphSearch.fill(coachTitle);
  await expect(page.getByText("1 match · non-matches dimmed", { exact: true })).toBeVisible();
  await app.navigate("Inbox");
  await expect(page.getByText(userTitle, { exact: true })).toBeHidden();
  await app.navigate("All Items");
  await page.locator("main").getByRole("button", { name: /^done$/i }).click();
  await expect(page.getByText(coachTitle, { exact: true })).toBeVisible();
  await page.getByText(coachTitle, { exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("heading", { name: coachTitle, exact: true })).toBeVisible();
});

test("one stale ordinary save reports once, retains its draft, and links to an owned receipt", async ({ page }) => {
  const app = new InboxPage(page);
  await app.goto();
  const original = await app.seed({ title: InboxPage.unique("single refusal"), type: "note" });
  await app.reload(); await app.navigate("Inbox");
  await app.row(original.title).getByTitle("Edit", { exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.locator("input").first().fill("Retained local title");
  const remote = await page.request.patch(`/api/items/${original.id}`, { data: { revision: original.revision, title: "Remote title" } });
  expect(remote.ok()).toBeTruthy();
  const refusal = page.waitForResponse((r) => r.request().method() === "PATCH" && r.url().endsWith(`/api/items/${original.id}`));
  await dialog.getByRole("button", { name: "Save changes" }).click();
  const response = await refusal;
  expect(response.status()).toBe(409);
  const result = await response.json();
  expect(result).toMatchObject({ conflict: true, currentRevision: original.revision + 1, receiptId: expect.any(String) });
  await expect(dialog.locator("input").first()).toHaveValue("Retained local title");
  await expect(page.locator("[data-sonner-toast]")).toHaveCount(1);
  await expect(page.locator("[data-sonner-toast]")).toContainText("This Item changed");
  const href = `/api/receipts/${encodeURIComponent(result.receiptId)}`;
  await expect(dialog.getByRole("link", { name: "View receipt" })).toHaveAttribute("href", href);
  const receipt = await page.request.get(href);
  expect(receipt.status()).toBe(200);
  expect(await receipt.json()).toMatchObject({ receipt: { ok: false, conflict: true, currentRevision: original.revision + 1 } });
  expect((await (await page.request.get(`/api/items/${original.id}`)).json()).title).toBe("Remote title");
});
