import { z } from "zod";
import {
  id,
  instant,
  localDate,
  timezone,
  revision,
  itemInput,
  projectInput,
  tagInput,
  recurrenceRule,
  reviewInput,
  activityInput,
} from "./contracts";
const stamp = { createdAt: instant },
  updated = { ...stamp, updatedAt: instant },
  demo = { demoBatchId: id.nullable() };
const maybeTime = instant.nullable();
